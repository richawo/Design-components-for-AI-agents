import assert from "node:assert/strict";
import { launchChromium } from "../../scripts/lib/browser.mjs";

const base = process.env.TEST_BASE || "http://localhost:3227";
const browser = await launchChromium();
try {
  for (const mobile of [false, true]) {
    const page = await browser.newPage({ viewport: { width: mobile ? 390 : 1440, height: 900 }, deviceScaleFactor: mobile ? 2 : 1, reducedMotion: "reduce" });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.addInitScript(() => {
      window.__rasterCount = 0;
      const create = CanvasRenderingContext2D.prototype.createImageData;
      CanvasRenderingContext2D.prototype.createImageData = function (...args) { window.__rasterCount++; return create.apply(this, args); };
    });
    await page.goto(`${base}/components`);
    await page.waitForFunction(() => document.querySelector("main canvas")?.style.opacity === "1");
    await page.waitForTimeout(500);
    assert.equal(await page.evaluate(() => window.__rasterCount), 1, "one initial raster, including the first resize notification");
    async function checkPixels() {
      assert.equal(await page.evaluate(() => {
        const actual = document.querySelector("main canvas");
        const rect = actual.parentElement.getBoundingClientRect();
        const cell = 3, dpr = Math.min(devicePixelRatio || 1, 2);
        const w = Math.max(1, Math.ceil(rect.width / cell)), h = Math.max(1, Math.ceil(rect.height / cell));
        // Original raster recipe, independent of the new observer scheduling.
        const bayer = Float32Array.from([0,32,8,40,2,34,10,42,48,16,56,24,50,18,58,26,12,44,4,36,14,46,6,38,60,28,52,20,62,30,54,22,3,35,11,43,1,33,9,41,51,19,59,27,49,17,57,25,15,47,7,39,13,45,5,37,63,31,55,23,61,29,53,21], n => (n + .5) / 64);
        const alpha = [0, .035, .07, .115];
        const off = document.createElement("canvas"); off.width = w; off.height = h;
        const ctx = off.getContext("2d"), data = ctx.createImageData(w, h);
        for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
          const dx = (x - w / 2) / Math.min(w * .42, 620 / cell), dy = (y + h * .06) / Math.min(h * .62, 520 / cell);
          const q = Math.max(0, 1 - Math.sqrt(dx * dx + dy * dy)) ** 1.8 * 3, lo = Math.floor(q);
          const level = Math.min(3, lo + (q - lo > bayer[(y & 7) * 8 + (x & 7)] ? 1 : 0)), i = (y * w + x) * 4;
          data.data.set([255, 255, 255, Math.round(alpha[level] * 255)], i);
        }
        ctx.putImageData(data, 0, 0);
        const reference = document.createElement("canvas"); reference.width = Math.round(w * cell * dpr); reference.height = Math.round(h * cell * dpr);
        const ref = reference.getContext("2d"); ref.imageSmoothingEnabled = false; ref.drawImage(off, 0, 0, reference.width, reference.height);
        if (actual.width !== reference.width || actual.height !== reference.height) return -1;
        const a = actual.getContext("2d").getImageData(0, 0, actual.width, actual.height).data, b = ref.getImageData(0, 0, reference.width, reference.height).data;
        return a.reduce((differences, value, i) => differences + Number(value !== b[i]), 0);
      }), 0, "the background pixels must match the original at the same size and DPR");
    }
    await checkPixels();
    // Ignore the reference raster generated by the pixel comparison itself.
    const before = await page.evaluate(() => window.__rasterCount);
    await page.setViewportSize({ width: mobile ? 430 : 1200, height: 900 });
    await page.waitForFunction(before => window.__rasterCount > before, before);
    await page.waitForTimeout(300);
    assert.equal(await page.evaluate(() => window.__rasterCount), before + 1, "one redraw for a changed size");
    await checkPixels();
    await page.screenshot({ path: `test-results/site-performance/gallery-background-${mobile ? "mobile" : "desktop"}.png` });
    assert.deepEqual(errors, []);
    await page.close();
  }
  console.log("Desktop/mobile: one initial draw, one resize draw, exact original background pixels at DPR 1 and 2.");
} finally { await browser.close(); }
