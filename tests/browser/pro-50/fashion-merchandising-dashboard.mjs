import { check as checkContrast } from '../review/fashion-merchandising-contrast.mjs';
export async function check({ page, mount, assert }) {
  const styles = [{ id: "slow", name: "Ribbed crew", category: "Knitwear", revenueMinor: 10000, priceMinor: 5000, sizes: [{ size: "S", received: 50, sold: 5 }, { size: "M", received: 50, sold: 5 }], weekly: [2,2,2,2,2] }, { id: "fast", name: "Cotton tee", category: "Jersey", revenueMinor: 80000, priceMinor: 2000, sizes: [{ size: "M", received: 100, sold: 80 }], weekly: [15,15,15,15,20] }];
  const collections = [{ id: "autumn", name: "Autumn", season: "AW26", week: 5, seasonWeeks: 10, targetSellThrough: 0.8, styles }, { id: "empty", name: "Resort", season: "27", styles: [] }];
  await mount(`window.proposals=[];window.fail=true;window.selected=[];createRoot(document.getElementById('root')).render(<Subject.MerchandisingDashboard collections={${JSON.stringify(collections)}} onSelectStyle={id=>window.selected.push(id)} onSendMarkdowns={async p=>{window.proposals.push(p);if(window.fail)throw Error('Pricing is offline');await new Promise(resolve=>window.releaseProposal=resolve)}}/>);`);
  const slow = page.locator('[data-demo="style-slow"]');
  await slow.focus();
  await page.keyboard.press("Enter");
  assert.equal(await page.evaluate(() => window.selected.at(-1)), "slow");
  const curve = page.getByRole("group", { name: /Sell-through by week/ });
  await curve.focus();
  await page.keyboard.press("Home");
  await page.getByText(/Wk 0 ·/).waitFor();
  await page.keyboard.press("ArrowRight");
  await page.getByText(/Wk 1 ·/).waitFor();
  await page.keyboard.press("End");
  await page.getByText(/Wk 5 ·/).waitFor();
  const include = page.locator('[data-demo="include-slow"]');
  assert.equal(await include.isChecked(), true);
  await include.uncheck();
  assert.equal(await page.locator('[data-demo="send"]').isDisabled(), true);
  await include.check();
  await page.locator('[data-demo="send"]').click();
  await page.getByRole("alert").filter({ hasText: "Pricing is offline" }).waitFor();
  assert.equal(await include.isChecked(), true);
  await page.evaluate(() => window.fail = false);
  await page.locator('[data-demo="send"]').click();
  await page.getByRole("button", { name: "Sending", exact: true }).waitFor();
  assert.equal(await page.getByRole("radio", { name: "Resort", exact: true }).isDisabled(), true);
  await page.evaluate(() => window.releaseProposal());
  await page.getByRole("status").filter({ hasText: "Sent to pricing review" }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.proposals[1]), { collectionId: "autumn", styles: [{ styleId: "slow", onHand: 90, coverWeeks: 45, sellThrough: 0.1 }], onHandValueMinor: 450000 });
  const autumn = page.getByRole("radio", { name: "Autumn", exact: true });
  await autumn.focus();
  await page.keyboard.press("ArrowRight");
  await page.getByText("No styles selling in this collection yet", { exact: true }).waitFor();
  await mount(`createRoot(document.getElementById('root')).render(<Subject.MerchandisingDashboard collections={[{id:'bad',name:'Bad',season:'26',styles:[{id:'x',name:'X',category:'A',revenueMinor:100,sizes:[{size:'M',received:0,sold:1}]}]}]}/>);`);
  await page.getByRole("status").filter({ hasText: /invalid|excluded|stock/ }).waitFor();
  assert.doesNotMatch(await page.locator("section").first().innerText(), /NaN|Infinity/);
  await checkContrast({ page, mount, assert });
}
