export async function check({ page, mount, assert }) {
  const categories = [{ id: "knit", name: "Knitwear", styles: 1, unitsPerStyle: 10, costMinor: 1000, retailMinor: 5000, ladder: { good: { costMinor: 800, retailMinor: 4000 }, better: { costMinor: 1000, retailMinor: 5000 }, best: { costMinor: 1500, retailMinor: 6000 } }, options: [{ id: "crew", name: "Ribbed crew", tier: "better", colour: "Camel", hex: "#b98a5a" }] }];
  const props = `categories={${JSON.stringify(categories)}}`;
  await mount(`window.plans=[];window.fail=true;createRoot(document.getElementById('root')).render(<Subject.CollectionLinePlan ${props} onSave={async p=>{window.plans.push(p);if(window.fail)throw Error('Buying is offline')}}/>);`);
  await page.locator('[data-demo="option-crew"]').focus();
  await page.keyboard.press("Enter");
  const better = page.getByRole("radio", { name: /Better/ }).first();
  await better.focus();
  await page.keyboard.press("ArrowRight");
  assert.equal(await page.getByRole("radio", { name: /Best/ }).first().getAttribute("aria-checked"), "true");
  await page.getByRole("radio", { name: "Ecru", exact: true }).click();
  const save = page.locator('[data-demo="save"]');
  await save.click();
  await page.getByRole("alert").filter({ hasText: "Buying is offline" }).waitFor();
  assert.equal(await page.locator('[data-demo="option-crew"]').getAttribute("aria-label"), "Ribbed crew, Ecru, Best");
  await page.evaluate(() => window.fail = false);
  await page.getByRole("button", { name: "Save again", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Line plan saved" }).waitFor();
  const plan = await page.evaluate(() => window.plans[1]);
  assert.equal(plan.costMinor, 15000);
  assert.equal(plan.retailMinor, 60000);
  assert.equal(plan.totalUnits, 10);
  assert.equal(plan.categories[0].options[0].tier, "best");
  assert.equal(plan.categories[0].options[0].colour, "Ecru");
  await page.locator('[data-demo="add-knit"]').click();
  await page.locator('[data-demo="option-knit-new-1"]').waitFor();
  await page.locator('[data-demo="option-knit-new-1"]').press("Delete");
  await page.locator('[data-demo="option-crew"]').press("Delete");
  assert.equal(await page.getByRole("button",{name:"Ribbed crew, Ecru, Best",exact:true}).count(), 0);
  await page.locator('[data-demo="add-knit"]').click();
  assert.equal(await save.isEnabled(), true, "A replacement style is an unsaved change even when the count is unchanged");
  await page.getByRole("button", { name: "Discard", exact: true }).click();
  await page.getByText("No changes since the last save.", { exact: true }).waitFor();

  await mount(`createRoot(document.getElementById('root')).render(<Subject.CollectionLinePlan ${props} budgetMinor={1000} onSave={()=>{}}/>);`);
  assert.match(await page.locator("section").first().innerText(), /over the cost budget/);
  assert.equal(await page.locator('[data-demo="save"]').isDisabled(), true);
  await mount(`createRoot(document.getElementById('root')).render(<Subject.CollectionLinePlan categories={[]} onSave={()=>{}}/>);`);
  assert.doesNotMatch(await page.locator("section").first().innerText(), /NaN|Infinity/);
  assert.equal(await page.locator('[data-demo="save"]').count(), 0);
  await mount(`createRoot(document.getElementById('root')).render(<Subject.CollectionLinePlan ${props} budgetMinor={Infinity}/>);`);
  await page.getByRole("alert").filter({ hasText: "Set a valid cost budget" }).waitFor();
}
