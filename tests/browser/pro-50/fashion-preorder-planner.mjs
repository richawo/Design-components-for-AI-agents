export async function check({ page, mount, assert }) {
  const drop = { id: "crew", name: "Ribbed crew", sku: "FN27-KN212", garment: "crew", colourway: "Camel", hex: "#b98a5a", priceMinor: 1000, opensOn: "2026-10-01", closesOn: "2026-10-05", ships: "November", factory: "North Mill" };
  const sizes = [{ id: "s", label: "S", preorders: 4 }, { id: "m", label: "M", preorders: 6 }];
  const props = `{...${JSON.stringify({ drop, sizes, daily: [4,6], minimumUnits: 5, maximumUnits: 20, packMultiple: 5, initialCapUnits: 10 })}}`;
  await mount(`window.decisions=[];window.fail=true;window.reopens=[];window.reopenFails=true;createRoot(document.getElementById('root')).render(<Subject.PreorderPlanner ${props} onClose={async p=>{window.decisions.push(p);if(window.fail)throw Error('Factory is offline')}} onReopen={async id=>{window.reopens.push(id);if(window.reopenFails)throw Error('Window is locked')}}/>);`);
  const cap = page.getByRole("slider", { name: "Production cap", exact: true });
  await cap.focus();
  await page.keyboard.press("ArrowUp");
  assert.equal(await cap.getAttribute("aria-valuenow"), "15");
  await page.keyboard.press("Home");
  assert.equal(await cap.getAttribute("aria-valuenow"), "5");
  await page.keyboard.press("End");
  assert.equal(await cap.getAttribute("aria-valuenow"), "20");
  await page.keyboard.press("ArrowDown");
  await page.locator('[data-demo="close"]').click();
  await page.getByText("Close preorders now?", { exact: true }).waitFor();
  assert.equal(await cap.getAttribute("aria-disabled"), "true");
  await page.locator('[data-demo="confirm-close"]').click();
  await page.getByRole("alert").filter({ hasText: "Factory is offline. Nobody was charged and your cap is kept" }).waitFor();
  assert.equal(await cap.getAttribute("aria-valuenow"), "15");
  await page.evaluate(() => window.fail = false);
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Preorders closed · 15 units ordered from North Mill" }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.decisions[1]), { dropId: "crew", productionUnits: 15, preorders: 10, confirmed: 10, waitlisted: 0, launchStock: 5, chargedMinor: 10000, currency: "GBP", bySize: [{ sizeId: "s", preorders: 4, production: 6, waitlisted: 0 }, { sizeId: "m", preorders: 6, production: 9, waitlisted: 0 }] });
  await page.getByRole("button", { name: "Reopen", exact: true }).click();
  await page.getByRole("alert").filter({hasText:"Preorders remain closed: Window is locked."}).waitFor();
  await page.evaluate(() => window.reopenFails = false);
  await page.getByRole("button", { name: "Reopen", exact: true }).click();
  await page.locator('[data-demo="close"]').waitFor();
  assert.deepEqual(await page.evaluate(() => window.reopens), ["crew", "crew"]);

  await mount(`createRoot(document.getElementById('root')).render(<Subject.PreorderPlanner ${props} packMultiple={0}/>);`);
  await page.getByRole("alert").filter({ hasText: "don’t leave a quantity the factory can make" }).waitFor();
  assert.equal(await page.locator('[data-demo="close"]').isDisabled(), true);
  await mount(`createRoot(document.getElementById('root')).render(<Subject.PreorderPlanner ${props} daily={[1]}/>);`);
  await page.getByRole("alert").filter({ hasText: "Preorders by size add up to 10, but the daily count is 1" }).waitFor();
  await mount(`createRoot(document.getElementById('root')).render(<Subject.PreorderPlanner drop={${JSON.stringify(drop)}} sizes={[]} daily={[]}/>);`);
  await page.getByText("No preorders yet", { exact: true }).waitFor();
  assert.equal(await page.locator('[data-demo="close"]').isDisabled(), true);
}
