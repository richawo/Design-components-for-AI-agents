export async function check({ page, mount, assert }) {
  const versions = `const fields=[{id:'name',label:'Event name'},{id:'description',label:'Description',multiline:true},{id:'venue',label:'Venue'}];const draft={id:'draft-4',author:'You',savedAt:'14:02',values:{name:'Autumn programme',description:'Keep this local draft.',venue:'Studio'}};const latest={id:'server-7',author:'Ada Vale',savedAt:'14:03',values:{name:'October programme',description:'Saved description.',venue:'Studio'}};`;
  await mount(`${versions}window.rescueJobs=[];window.rescueChoices=[];createRoot(document.getElementById('root')).render(<Subject.FormsDraftRescue fields={fields} draft={draft} latest={latest} onChoicesChange={choices=>window.rescueChoices.push({...choices})} onResolve={(resolution,signal)=>new Promise((resolve,reject)=>window.rescueJobs.push({resolution:structuredClone(resolution),signal,resolve,reject}))}/>);`);
  const draftName = page.locator('[data-demo="rescue-ghost-name"]');
  await draftName.focus();
  await draftName.press('Enter');
  await page.waitForFunction(() => window.rescueChoices.length === 1);
  assert.equal(await page.evaluate(() => window.rescueChoices[0].name), 'draft');
  const restore = page.locator('[data-demo="rescue-restore"]');
  await restore.focus();
  await restore.press('Space');
  await page.waitForFunction(() => window.rescueJobs.length === 1);
  assert.equal(await restore.getAttribute('aria-busy'), 'true');
  assert.equal(await restore.isDisabled(), true);
  await page.evaluate(() => window.rescueJobs[0].reject(Error('The saved version is temporarily unavailable.')));
  await page.getByRole('alert').filter({ hasText: 'Every choice is kept.' }).waitFor();
  await restore.focus();
  await restore.press('Enter');
  await page.waitForFunction(() => window.rescueJobs.length === 2);
  const expected = { draftVersionId: 'draft-4', latestVersionId: 'server-7', decisions: { name: 'draft', description: 'latest' }, values: { name: 'Autumn programme', description: 'Saved description.', venue: 'Studio' } };
  assert.deepEqual(await page.evaluate(() => window.rescueJobs.map(job => job.resolution)), [expected, expected]);
  await page.evaluate(() => window.rescueJobs[1].resolve());
  await page.getByRole('button', { name: 'Restored', exact: true }).waitFor();
  await mount(`${versions}window.rescueJobs=[];createRoot(document.getElementById('root')).render(<Subject.FormsDraftRescue fields={fields} draft={draft} latest={latest} onResolve={(resolution,signal)=>new Promise((resolve,reject)=>window.rescueJobs.push({resolution,signal,resolve,reject}))}/>);`);
  await restore.click();
  await page.waitForFunction(() => window.rescueJobs.length === 1);
  await page.getByRole('button', { name: 'Cancel', exact: true }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => window.rescueJobs[0].signal.aborted), true);
  await restore.click();
  await page.waitForFunction(() => window.rescueJobs.length === 2);
  await page.evaluate(() => window.rescueJobs[0].resolve());
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await restore.getAttribute('aria-busy'), 'true');
  await page.evaluate(() => window.rescueJobs[1].resolve());
  await page.getByRole('button', { name: 'Restored', exact: true }).waitFor();
  await mount(`${versions}createRoot(document.getElementById('root')).render(<Subject.FormsDraftRescue fields={[]} draft={draft} latest={latest} disabled/>);`);
  assert.equal(await page.locator('[data-demo^="rescue-ghost-"]').count(), 0);
  assert.equal(await restore.isDisabled(), true);
  assert.match(await page.locator('#root').innerText(), /Read only/);
}
