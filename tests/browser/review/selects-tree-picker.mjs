export async function check({ page, mount, assert }) {
  const nodes = `[{id:'design',label:'Design',children:[{id:'brand',label:'Brand',count:2},{id:'locked',label:'Locked design',disabled:true,count:1}]},{id:'sales',label:'Sales',children:[{id:'sales-emea',label:'EMEA',count:3}]}]`;
  await mount(`window.treeSelections=[];createRoot(document.getElementById('root')).render(<Subject.SelectsTreePicker nodes={${nodes}} defaultValue={['locked']} defaultOpen onValueChange={ids=>window.treeSelections.push([...ids])}/>);`);
  const search = page.locator('[data-demo="tree-search"]');
  await search.focus();
  await search.press('ArrowDown');
  await search.press('Enter');
  await page.waitForFunction(() => window.treeSelections.length === 1);
  assert.deepEqual(await page.evaluate(() => window.treeSelections[0]), ['brand', 'locked']);
  await search.press('ArrowRight');
  const locked = page.locator('[data-demo="tree-row-locked"]');
  await locked.waitFor();
  assert.equal(await locked.getAttribute('aria-disabled'), 'true');
  await search.press('Enter');
  await page.waitForFunction(() => window.treeSelections.length === 2);
  assert.deepEqual(await page.evaluate(() => window.treeSelections[1]), ['locked'], 'Toggling a group preserves a locked selected leaf');
  await search.press('Enter');
  await page.waitForFunction(() => window.treeSelections.length === 3);
  assert.deepEqual(await page.evaluate(() => window.treeSelections[2]), ['brand', 'locked']);
  await search.fill('EMEA');
  await page.locator('[data-demo="tree-row-sales-emea"]').waitFor();
  await search.press('Enter');
  await page.waitForFunction(() => window.treeSelections.length === 4);
  assert.deepEqual(await page.evaluate(() => window.treeSelections[3]), ['brand', 'locked', 'sales-emea']);
  assert.equal(await search.evaluate(node => node === document.activeElement), true);
  await search.fill('no-matching-team');
  await page.waitForFunction(() => document.querySelectorAll('[role="treeitem"]').length === 0);
  assert.equal(await page.getByRole('treeitem').count(), 0);
  await search.press('Escape');
  assert.equal(await search.inputValue(), '');
  await search.press('Escape');
  await page.getByRole('tree').waitFor({ state: 'hidden' });
  await mount(`createRoot(document.getElementById('root')).render(<Subject.SelectsTreePicker nodes={[]} defaultOpen/>);`);
  assert.equal(await page.getByRole('treeitem').count(), 0);
  await mount(`window.treeRetries=0;function Host(){const[status,setStatus]=React.useState('error');return <Subject.SelectsTreePicker nodes={${nodes}} defaultOpen status={status} onRetry={()=>{window.treeRetries++;setStatus('ready')}}/>};createRoot(document.getElementById('root')).render(<Host/>);`);
  await page.getByRole('button', { name: 'Try again', exact: true }).focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => window.treeRetries === 1);
  await page.locator('[data-demo="tree-row-design"]').waitFor();
}
