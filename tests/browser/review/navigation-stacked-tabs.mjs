export async function check({ page, mount, assert }) {
  await mount(`window.closeJobs=[];window.restoreJobs=[];window.orderJobs=[];const items=[{id:'notes',label:'Notes',dirty:true,content:<textarea aria-label="Notes draft" defaultValue="Original notes"/>},{id:'summary',label:'Summary',content:<textarea aria-label="Summary draft" defaultValue="Original summary"/>}];createRoot(document.getElementById('root')).render(<Subject.NavigationStackedTabs items={items} onCloseRequest={(item,signal)=>new Promise((resolve,reject)=>window.closeJobs.push({id:item.id,signal,resolve,reject}))} onRestoreRequest={(item,signal)=>new Promise((resolve,reject)=>window.restoreJobs.push({id:item.id,signal,resolve,reject}))} onOrderChange={(ids,signal)=>new Promise((resolve,reject)=>window.orderJobs.push({ids:[...ids],signal,resolve,reject}))}/>);`);
  const notes = page.locator('[data-demo="tab-notes"]');
  const summary = page.locator('[data-demo="tab-summary"]');
  await page.getByRole('textbox', { name: 'Notes draft', exact: true }).fill('Keep these edited notes.');
  await notes.focus();
  await notes.press('Delete');
  await page.getByRole('dialog').waitFor();
  await page.locator('[data-demo="keep-open"]').focus();
  await page.keyboard.press('Enter');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('textbox', { name: 'Notes draft', exact: true }).inputValue(), 'Keep these edited notes.');
  assert.equal(await page.evaluate(() => window.closeJobs.length), 0);
  await notes.focus();
  await notes.press('ArrowRight');
  await page.getByRole('textbox', { name: 'Summary draft', exact: true }).fill('Keep the summary draft.');
  await summary.focus();
  await summary.press('Delete');
  await page.waitForFunction(() => window.closeJobs.length === 1);
  await page.evaluate(() => window.closeJobs[0].reject(Error('Document service unavailable')));
  const retry = page.locator('[data-demo="retry-action"]');
  await retry.waitFor();
  assert.equal(await summary.getAttribute('aria-selected'), 'true');
  assert.equal(await page.getByRole('textbox', { name: 'Summary draft', exact: true }).inputValue(), 'Keep the summary draft.');
  await retry.focus();
  await retry.press('Space');
  await page.waitForFunction(() => window.closeJobs.length === 2);
  assert.deepEqual(await page.evaluate(() => window.closeJobs.map(job => job.id)), ['summary', 'summary']);
  await page.evaluate(() => window.closeJobs[1].resolve());
  await summary.waitFor({ state: 'hidden' });
  await page.locator('[data-demo="undo-close"]').focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => window.restoreJobs.length === 1);
  await page.evaluate(() => window.restoreJobs[0].reject(Error('Document archive unavailable')));
  await retry.waitFor();
  await retry.focus();
  await retry.press('Enter');
  await page.waitForFunction(() => window.restoreJobs.length === 2);
  assert.deepEqual(await page.evaluate(() => window.restoreJobs.map(job => job.id)), ['summary', 'summary']);
  await page.evaluate(() => window.restoreJobs[1].resolve());
  await page.getByRole('textbox', { name: 'Summary draft', exact: true }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: 'Summary draft', exact: true }).inputValue(), 'Keep the summary draft.');
  await summary.focus();
  await summary.press('Control+Shift+ArrowLeft');
  await page.waitForFunction(() => window.orderJobs.length === 1);
  assert.deepEqual(await page.evaluate(() => window.orderJobs[0].ids), ['summary', 'notes']);
  await page.evaluate(() => window.orderJobs[0].reject(Error('Order service unavailable')));
  await retry.waitFor();
  await page.waitForFunction(() => document.querySelector('[role="tab"]').dataset.demo === 'tab-notes');
  await retry.focus();
  await retry.press('Enter');
  await page.waitForFunction(() => window.orderJobs.length === 2);
  assert.deepEqual(await page.evaluate(() => window.orderJobs[1].ids), ['summary', 'notes']);
  await page.evaluate(() => window.orderJobs[1].resolve());
  await page.waitForFunction(() => document.querySelector('[role="tab"]').dataset.demo === 'tab-summary');
  await mount(`createRoot(document.getElementById('root')).render(<Subject.NavigationStackedTabs items={[]}/>);`);
  assert.equal(await page.getByRole('tab').count(), 0);
}
