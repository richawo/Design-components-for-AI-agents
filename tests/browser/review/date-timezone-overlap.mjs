export async function check({ page, mount, assert }) {
  const people = `[{id:'london',name:'Ada Vale',city:'London',timeZone:'Europe/London',start:'09:00',end:'17:00'},{id:'berlin',name:'Ben Ito',city:'Berlin',timeZone:'Europe/Berlin',start:'09:00',end:'17:00'}]`;
  await mount(`window.slotJobs=[];window.slotChanges=[];window.includedChanges=[];createRoot(document.getElementById('root')).render(<Subject.DateTimezoneOverlap date="2026-10-20" people={${people}} onIncludedChange={ids=>window.includedChanges.push([...ids])} onSlotChange={slot=>window.slotChanges.push(structuredClone(slot))} onPropose={slot=>new Promise((resolve,reject)=>window.slotJobs.push({slot:structuredClone(slot),resolve,reject}))}/>);`);
  const slot = page.locator('[data-demo="tz-slot"]');
  await slot.focus();
  await slot.press('Home');
  await page.waitForFunction(() => window.slotChanges.length === 1);
  const first = await page.evaluate(() => window.slotChanges[0]);
  assert.equal(first.start, '2026-10-20T08:00:00.000Z');
  assert.equal(first.end, '2026-10-20T08:30:00.000Z');
  assert.deepEqual(first.participantIds, ['london', 'berlin']);
  await slot.press('ArrowRight');
  await page.waitForFunction(() => window.slotChanges.length === 2);
  assert.equal(Date.parse(await page.evaluate(() => window.slotChanges[1].start)) - Date.parse(first.start), 15 * 60_000);
  const berlin = page.locator('[data-demo="tz-person-berlin"]:visible').first();
  await berlin.focus();
  await berlin.press('Space');
  await page.waitForFunction(() => window.includedChanges.length === 1);
  assert.deepEqual(await page.evaluate(() => window.includedChanges[0]), ['london']);
  const propose = page.locator('[data-demo="tz-propose"]');
  await propose.focus();
  await propose.press('Enter');
  await page.waitForFunction(() => window.slotJobs.length === 1);
  assert.equal(await propose.getAttribute('aria-busy'), 'true');
  await propose.press('Enter');
  assert.equal(await page.evaluate(() => window.slotJobs.length), 1);
  await page.evaluate(() => window.slotJobs[0].reject(Error('Calendar is unavailable')));
  await page.waitForFunction(() => document.querySelector('[data-demo="tz-propose"]').textContent.includes('Try again'));
  await propose.focus();
  await propose.press('Space');
  await page.waitForFunction(() => window.slotJobs.length === 2);
  const requests = await page.evaluate(() => window.slotJobs.map(job => job.slot));
  assert.deepEqual(requests[0], requests[1]);
  assert.deepEqual(requests[1].participantIds, ['london']);
  assert.equal(requests[1].durationMinutes, 30);
  await page.evaluate(() => window.slotJobs[1].resolve());
  await page.getByRole('button', { name: 'Invites sent', exact: true }).waitFor();
  await mount(`createRoot(document.getElementById('root')).render(<Subject.DateTimezoneOverlap people={[]} onPropose={()=>{throw Error('No participants must not submit')}}/>);`);
  assert.equal(await page.locator('[data-demo="tz-propose"]').isDisabled(), true);
  assert.equal(await page.locator('[data-demo="tz-jump"]').isDisabled(), true);
  assert.match(await page.locator('#root').innerText(), /Nobody included/);
  await mount(`createRoot(document.getElementById('root')).render(<Subject.DateTimezoneOverlap people={[]} anchorZone="Not/AZone" date="invalid" durationMinutes={NaN} durations={[]}/>);`);
  assert.doesNotMatch(await page.locator('#root').innerText(), /NaN|Invalid Date|Infinity/);
}
