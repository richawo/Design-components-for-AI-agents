export async function check({ page, mount, assert }) {
  await mount(`window.railJobs=[];const sections=[{id:'projects',label:'Projects',icon:<span>P</span>,items:[{id:'one',label:'Project one'},{id:'locked',label:'Unavailable project',disabled:true,disabledReason:'Archived'},{id:'two',label:'Project two'}]}];function Host(){const[content,setContent]=React.useState('Project one is open.');return <Subject.NavigationContextRail sections={sections} defaultValue={{sectionId:'projects',itemId:'one'}} onValueChange={(selection,item,signal)=>new Promise((resolve,reject)=>window.railJobs.push({selection:{...selection},itemId:item.id,signal,reject,resolve:()=>{if(!signal.aborted)setContent(item.label+' is open.');resolve()}}))}><p>{content}</p></Subject.NavigationContextRail>};createRoot(document.getElementById('root')).render(<Host/>);`);
  const section = page.locator('[data-demo="section-projects"]');
  await section.focus();
  await section.press('Enter');
  const one = page.locator('[data-demo="item-one"]');
  const two = page.locator('[data-demo="item-two"]');
  await one.waitFor();
  await one.focus();
  await one.press('ArrowDown');
  assert.equal(await two.evaluate(node => node === document.activeElement), true);
  await two.press('Space');
  await page.waitForFunction(() => window.railJobs.length === 1);
  assert.equal(await two.getAttribute('aria-busy'), 'true');
  assert.equal(await page.getByText('Project one is open.', { exact: true }).count(), 1);
  await page.evaluate(() => window.railJobs[0].reject(Error('Destination unavailable')));
  const retry = page.locator('[data-demo="retry-navigation"]');
  await retry.waitFor();
  assert.equal(await one.getAttribute('aria-current'), 'page');
  await retry.focus();
  await retry.press('Enter');
  await page.waitForFunction(() => window.railJobs.length === 2);
  assert.deepEqual(await page.evaluate(() => window.railJobs.map(({ selection, itemId }) => ({ selection, itemId }))), [{ selection: { sectionId: 'projects', itemId: 'two' }, itemId: 'two' }, { selection: { sectionId: 'projects', itemId: 'two' }, itemId: 'two' }]);
  await page.evaluate(() => window.railJobs[1].resolve());
  await page.getByText('Project two is open.', { exact: true }).waitFor();
  await page.getByRole('dialog', { name: 'Projects destinations', exact: true }).waitFor({ state: 'hidden' });
  await section.click();
  await page.getByRole('dialog', { name: 'Projects destinations', exact: true }).waitFor();
  await one.click();
  await page.waitForFunction(() => window.railJobs.length === 3);
  await two.click();
  assert.equal(await page.evaluate(() => window.railJobs[2].signal.aborted), true);
  await page.evaluate(() => window.railJobs[2].resolve());
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.getByText('Project two is open.', { exact: true }).count(), 1);
  await page.getByRole('dialog', { name: 'Projects destinations', exact: true }).waitFor({ state: 'hidden' });
  await section.click();
  await page.getByRole('dialog', { name: 'Projects destinations', exact: true }).waitFor();
  assert.equal(await two.getAttribute('aria-current'), 'page');
  assert.equal(await page.evaluate(() => window.railJobs.length), 3);
  await mount(`createRoot(document.getElementById('root')).render(<Subject.NavigationContextRail sections={[]}><p>Workspace remains available.</p></Subject.NavigationContextRail>);`);
  assert.equal(await page.locator('[data-demo^="section-"]').count(), 0);
  assert.equal(await page.getByText('Workspace remains available.', { exact: true }).isVisible(), true);
}
