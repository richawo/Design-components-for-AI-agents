export async function check({ page, mount, assert }) {
  const room = { id: "crit", title: "Design crit", time: "10:30", participants: [] };
  const devices = [{ id: "mic", group: "microphone", label: "Desk mic" }, { id: "desk", group: "speaker", label: "Desk speaker" }, { id: "headset", group: "speaker", label: "Headset" }, { id: "offline", group: "speaker", label: "Remote speaker", available: false }, { id: "front", group: "camera", label: "Front camera" }];
  const props = `room={${JSON.stringify(room)}} devices={${JSON.stringify(devices)}} checks={[]}`;
  await mount(`window.calls=[];window.signals=[];window.fail=true;window.changed=[];createRoot(document.getElementById('root')).render(<Subject.MobileMeetingPreflight ${props} onDeviceChange={(group,id)=>window.changed.push({group,id})} onJoin={async(p,signal)=>{window.calls.push(p);window.signals.push(signal);if(window.fail)throw Error('Offline');await new Promise(resolve=>window.finishJoin=resolve)}}/>);`);
  const mute = page.getByRole("switch", { name: "Microphone muted", exact: true });
  await mute.press("Enter");
  assert.equal(await mute.getAttribute("aria-checked"), "true");
  await page.getByRole("switch", { name: "Camera off", exact: true }).press("Space");
  await page.getByRole("switch", { name: "Background blur", exact: true }).press("Space");
  await page.getByRole("button", { name: /^Speaker: Desk speaker/ }).press("Enter");
  const headset = page.getByRole("radio", { name: "Headset", exact: true });
  assert.equal(await headset.getAttribute("aria-checked"), "false");
  assert.equal(await page.getByRole("radio", { name: "Remote speaker", exact: true }).isDisabled(), true);
  await headset.press("Space");
  await headset.waitFor({ state: "hidden" });
  const speaker = page.getByRole("button", { name: /^Speaker: Headset/ });
  assert.equal(await speaker.evaluate(el => el === document.activeElement), true);
  await speaker.press("Enter");
  await page.getByRole("radio", { name: "Headset", exact: true }).press("Escape");
  await headset.waitFor({ state: "hidden" });
  assert.equal(await speaker.evaluate(el => el === document.activeElement), true);
  await page.getByRole("button", { name: "Join now", exact: true }).press("Enter");
  await page.getByRole("button", { name: "Try joining again", exact: true }).waitFor();
  assert.equal(await mute.getAttribute("aria-checked"), "true");
  await page.evaluate(() => window.fail = false);
  await page.getByRole("button", { name: "Try joining again", exact: true }).press("Enter");
  await page.getByRole("button", { name: "Cancel joining", exact: true }).press("Enter");
  assert.equal(await page.evaluate(() => window.signals[1].aborted), true);
  await page.evaluate(() => window.finishJoin());
  await page.getByRole("button", { name: "Join now", exact: true }).waitFor();
  assert.equal(await page.getByText("You’re in", { exact: true }).count(), 0);
  await page.getByRole("button", { name: "Join now", exact: true }).press("Enter");
  await page.getByRole("button", { name: "Cancel joining", exact: true }).waitFor();
  await page.evaluate(() => window.finishJoin());
  await page.getByText("You’re in", { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.calls[2]), { roomId: "crit", muted: true, cameraOn: false, backgroundBlur: true, devices: { microphone: "mic", speaker: "headset", camera: null } });
  assert.deepEqual(await page.evaluate(() => window.changed), [{ group: "speaker", id: "headset" }]);
  await mount(`createRoot(document.getElementById('root')).render(<Subject.MobileMeetingPreflight devices={[]} checks={[]}/>);`);
  assert.equal(await page.getByRole("button", { name: "Join now", exact: true }).isDisabled(), true);
  await page.getByText("Choose a speaker to hear the call", { exact: true }).waitFor();
}
