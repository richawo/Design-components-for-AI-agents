export async function check({ page, mount, assert }) {
  const questions = `[{id:'kind',short:'Platform',kind:'choice',title:'Choose a platform',required:true,options:[{value:'web',label:'Website'},{value:'mobile',label:'Mobile app'}]},{id:'web-detail',short:'Website',kind:'text',title:'Website detail',required:true,showWhen:{questionId:'kind',equals:'web'}},{id:'mobile-detail',short:'Mobile',kind:'text',title:'Mobile detail',required:true,showWhen:{questionId:'kind',equals:'mobile'}},{id:'name',short:'Name',kind:'text',title:'Your name',required:true}]`;
  await mount(`window.surveyChanges=[];window.surveyJobs=[];createRoot(document.getElementById('root')).render(<Subject.FormsBranchingSurvey formId="regression-brief" recipient="Review team" questions={${questions}} autoAdvance={false} onAnswersChange={answers=>window.surveyChanges.push({...answers})} onSubmit={submission=>new Promise((resolve,reject)=>window.surveyJobs.push({submission:structuredClone(submission),resolve,reject}))}/>);`);
  const next = page.locator('[data-demo="survey-next"]');
  await next.focus();
  await next.press('Enter');
  await page.getByRole('alert').filter({ hasText: 'needs an answer' }).waitFor();
  const website = page.locator('[data-demo="choice-web"] input');
  await website.focus();
  await website.press('Space');
  assert.equal(await website.isChecked(), true);
  await next.focus();
  await next.press('Enter');
  const detail = page.locator('[data-demo="text-web-detail"]');
  await detail.waitFor();
  await detail.fill('Keep the prior website branch.');
  await next.click();
  await page.locator('[data-demo="text-name"]').fill('Ada Vale');
  await next.click();
  await page.getByRole('button', { name: 'Edit: Platform', exact: true }).focus();
  await page.keyboard.press('Enter');
  const mobile = page.locator('[data-demo="choice-mobile"] input');
  await mobile.waitFor();
  await mobile.focus();
  await mobile.press('Space');
  await next.click();
  await page.locator('[data-demo="text-mobile-detail"]').fill('  A compact mobile workflow.  ');
  await next.click();
  assert.equal(await page.locator('[data-demo="text-name"]').inputValue(), 'Ada Vale');
  await next.click();
  const submit = page.locator('[data-demo="survey-submit"]');
  await submit.focus();
  await submit.press('Enter');
  await page.waitForFunction(() => window.surveyJobs.length === 1);
  assert.equal(await submit.getAttribute('aria-busy'), 'true');
  await submit.press('Enter');
  assert.equal(await page.evaluate(() => window.surveyJobs.length), 1);
  await page.evaluate(() => window.surveyJobs[0].reject(Error('The briefing service is offline')));
  await page.getByRole('alert').filter({ hasText: 'Your answers are all here' }).waitFor();
  await submit.focus();
  await submit.press('Space');
  await page.waitForFunction(() => window.surveyJobs.length === 2);
  const expected = { formId: 'regression-brief', questionIds: ['kind', 'mobile-detail', 'name'], answers: { kind: 'mobile', 'mobile-detail': 'A compact mobile workflow.', name: 'Ada Vale' } };
  assert.deepEqual(await page.evaluate(() => window.surveyJobs.map(job => job.submission)), [expected, expected]);
  assert.equal(await page.evaluate(() => window.surveyChanges.at(-1)['web-detail']), 'Keep the prior website branch.');
  await page.evaluate(() => window.surveyJobs[1].resolve());
  await page.getByRole('heading', { name: 'Brief sent to Review team', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Start another brief', exact: true }).focus();
  await page.keyboard.press('Enter');
  await website.waitFor();
  assert.equal(await website.isChecked(), false);
  assert.deepEqual(await page.evaluate(() => window.surveyChanges.at(-1)), {});
  await mount(`window.emptySurveySubmits=0;createRoot(document.getElementById('root')).render(<Subject.FormsBranchingSurvey questions={[]} onSubmit={()=>{window.emptySurveySubmits++}}/>);`);
  assert.equal(await page.getByRole('radio').count(), 0);
  assert.equal(await page.getByRole('textbox').count(), 0);
  await page.locator('[data-demo="survey-next"]').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => window.emptySurveySubmits), 0);
}
