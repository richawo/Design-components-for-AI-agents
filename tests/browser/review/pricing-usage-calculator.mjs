export async function check({ page, mount, assert }) {
  const rates = `{currency:'USD',baseMinor:1000,includedUnits:100,blockUnits:10,blockPriceMinor:250,rounding:'started-block',unitLabel:'renders',periodLabel:'month'}`;
  await mount(`window.usageChanges=[];window.usageJobs=[];createRoot(document.getElementById('root')).render(<Subject.PricingUsageCalculator rates={${rates}} defaultQuantity={100} maxQuantity={1000} step={10} presets={[]} onQuantityChange={(quantity,estimate)=>window.usageChanges.push({quantity,estimate:structuredClone(estimate)})} onContinue={(quantity,estimate)=>new Promise((resolve,reject)=>window.usageJobs.push({quantity,estimate:structuredClone(estimate),resolve,reject}))}/>);`);
  const meter = page.locator('[data-demo="usage-range"]');
  await meter.focus();
  await meter.press('ArrowRight');
  await page.waitForFunction(() => window.usageChanges.length === 1);
  assert.equal(await page.evaluate(() => window.usageChanges[0].quantity), 110);
  assert.equal(await page.evaluate(() => window.usageChanges[0].estimate.totalMinor), 1250);
  const count = page.locator('[data-demo="usage-count"]');
  await count.fill('111');
  await count.press('Enter');
  await page.waitForFunction(() => window.usageChanges.length === 2);
  assert.equal(await page.evaluate(() => window.usageChanges[1].estimate.totalMinor), 1500);
  const next = page.locator('[data-demo="usage-continue"]');
  await next.focus();
  await next.press('Enter');
  await page.waitForFunction(() => window.usageJobs.length === 1);
  assert.equal(await next.getAttribute('aria-busy'), 'true');
  await page.evaluate(() => window.usageJobs[0].reject(Error('Fixture plan service unavailable')));
  await page.getByRole('alert').filter({ hasText: 'try again' }).waitFor();
  assert.equal(await count.inputValue(), '111');
  await next.focus();
  await next.press('Space');
  await page.waitForFunction(() => window.usageJobs.length === 2);
  const calls = await page.evaluate(() => window.usageJobs.map(({ quantity, estimate }) => ({ quantity, estimate })));
  assert.deepEqual(calls[0], calls[1]);
  assert.deepEqual(calls[1], { quantity: 111, estimate: { quantity: 111, included: 100, overage: 11, blocks: 2, overageMinor: 500, totalMinor: 1500 } });
  await page.evaluate(() => window.usageJobs[1].resolve());
  await page.getByRole('status').filter({ hasText: 'Plan saved with this estimate.' }).waitFor();
  await mount(`createRoot(document.getElementById('root')).render(<Subject.PricingUsageCalculator rates={null} presets={[]}/>);`);
  assert.equal(await next.count(), 0);
  assert.equal(await page.locator('[data-demo="usage-range"]').count(), 0);
  await mount(`window.invalidUsageSubmissions=0;createRoot(document.getElementById('root')).render(<Subject.PricingUsageCalculator rates={{...${rates},blockUnits:0}} presets={[]} onContinue={()=>{window.invalidUsageSubmissions++;throw Error('Invalid rates must not submit')}}/>);`);
  assert.equal(await next.isDisabled(), true);
  await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => window.invalidUsageSubmissions), 0);
  assert.doesNotMatch(await page.locator('#root').innerText(), /NaN|Infinity/);
}
