import assert from "node:assert/strict";
import fs from "node:fs";
import { launchChromium } from "../../scripts/lib/browser.mjs";
import { LOCALES } from "../../lib/blog/locales.mjs";

const base = process.env.TEST_BASE ?? "http://127.0.0.1:3000";
const output = "test-results/site-localisation";
fs.mkdirSync(output, { recursive: true });
const browser = await launchChromium();
const errors = [];
const results = [];
const settle = async (page) => {
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => [...document.querySelectorAll("h1, .site-in")].filter((element) => element.getBoundingClientRect().top < innerHeight).every((element) => Number(getComputedStyle(element).opacity) === 1));
};
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
  page.setDefaultTimeout(90_000);
  page.on("pageerror", (error) => errors.push({ url: page.url(), message: error.message }));
  for (const path of ["", "/components", "/blocks", "/pricing", "/docs", "/docs/agents", "/categories/charts", "/account"]) {
    const response = await page.goto(`${base}/fr${path}`, { waitUntil: "domcontentloaded", timeout: 120_000 });
    assert.equal(response.status(), 200, path);
    assert.equal(await page.locator("html").getAttribute("lang"), "fr-FR");
    assert.equal(await page.locator("link[rel=canonical]").getAttribute("href"), `https://design.yaps.ai/fr${path}`);
    assert.equal(await page.locator("header").first().locator("nav").first().locator('a[href="/fr/components"]').count(), 1);
    results.push({ path: `/fr${path}`, heading: await page.locator("h1").innerText() });
  }
  await page.goto(`${base}/fr/blog`, { waitUntil: "domcontentloaded" });
  const article = await page.locator('main a[href^="/fr/blog/"]').evaluateAll((links) => links.map((link) => link.getAttribute("href")).find((href) => !/\/(?:category|page)\/|\.[a-z0-9]+(?:[?#]|$)/i.test(href)));
  assert(article, "The French blog has an article link");
  await page.goto(`${base}${article}`, { waitUntil: "domcontentloaded" });
  const englishArticle = new URL(await page.locator('link[rel="alternate"][hreflang="en"]').getAttribute("href")).pathname;
  await page.locator("header").first().locator("[data-language-switcher] button").click();
  assert.equal(await page.locator('header a[lang="en"]').getAttribute("href"), englishArticle, "The header retains the blog's translated article slugs");
  await page.keyboard.press("Escape");
  await page.goto(`${base}/fr/components/chart-portfolio`, { waitUntil: "domcontentloaded" });
  await page.locator("#preview").scrollIntoViewIfNeeded();
  const iframe = page.locator("#preview iframe");
  assert.equal(await iframe.getAttribute("src"), "/fr/preview/chart-portfolio");
  const preview = iframe.contentFrame();
  await preview.locator('[data-preview-ready="true"]').waitFor();
  await preview.getByText("Le mois dernier", { exact: true }).waitFor();
  await preview.getByRole("radio", { name: "1W", exact: true }).click();
  await preview.getByText("La semaine dernière", { exact: true }).waitFor();
  await page.screenshot({ path: `${output}/french-component.png` });
  const registry = await (await page.request.get(`${base}/r/chart-portfolio.json`)).json();
  assert(registry.files[0].content.includes('locale = "en-US"'));
  assert(!registry.files[0].content.includes("useSiteI18n"));
  assert.equal((await page.request.get(`${base}/api/registry/block-music-workspace`)).status(), 401);
  await page.goto(`${base}/fr/components?category=charts&tier=free#main`, { waitUntil: "domcontentloaded" });
  await page.locator('[data-gallery-ready="true"]').waitFor();
  assert(page.url().includes("/fr/components?category=charts&tier=free#main"));
  const switcher = page.locator("header").first().getByRole("button", { name: /Choisir/ });
  await switcher.click();
  const german = page.locator('header nav a[lang="de-DE"]');
  assert.equal(await german.getAttribute("href"), "/de/components?category=charts&tier=free#main");
  await german.click();
  await page.waitForURL("**/de/components?category=charts&tier=free#main");
  await page.locator('[data-gallery-ready="true"]').waitFor();
  assert.equal(await page.locator("html").getAttribute("lang"), "de-DE");
  for (const width of [1440, 1024, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`${base}/de`, { waitUntil: "domcontentloaded" });
    await settle(page);
    assert(await page.locator("header").first().evaluate((header) => header.scrollWidth <= header.clientWidth + 1), `Header overflows at ${width}px`);
    await page.screenshot({ path: `${output}/german-header-${width}.png` });
  }
  const header = page.locator("header").first();
  await header.getByRole("button", { name: "Menü öffnen", exact: true }).click();
  await header.locator("[data-language-switcher] button").click();
  const french = header.locator('a[lang="fr-FR"]');
  await french.scrollIntoViewIfNeeded();
  assert(await french.evaluate((link) => {
    const box = link.getBoundingClientRect();
    return link.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2));
  }), "Language popup must remain above the open mobile menu");
  await page.keyboard.press("Escape");
  assert.equal(await header.locator("[data-language-switcher] button").getAttribute("aria-expanded"), "false");
  await page.keyboard.press("Escape");
  await page.goto(`${base}/ar/docs`, { waitUntil: "domcontentloaded" });
  assert.equal(await page.locator("html").getAttribute("dir"), "rtl");
  await settle(page);
  await page.screenshot({ path: `${output}/arabic-mobile.png` });
  const markdown = await page.request.get(`${base}/fr/docs/agents.md`);
  assert.equal(markdown.status(), 200);
  assert((await markdown.text()).includes("language: fr-FR"));
  await page.goto(`${base}/fr/missing-page`, { waitUntil: "domcontentloaded" });
  assert.notEqual(await page.locator("h1").innerText(), "This page could not be found.");
  assert(await page.getByRole("link").filter({ hasText: /composants/i }).count());
  await page.setViewportSize({ width: 1280, height: 900 });
  for (const language of LOCALES) {
    const path = language.code === "en" ? "" : `/${language.code}`;
    await page.goto(`${base}${path}`, { waitUntil: "domcontentloaded" });
    await settle(page);
    assert(await page.locator("header").first().evaluate((header) => header.scrollWidth <= header.clientWidth + 1), `${language.code} header overflows at 1280px`);
  }
  const billing = await page.request.get(`${base}/account?pending=1`, { maxRedirects: 0, headers: { Cookie: "design-locale=fr" } });
  assert.equal(billing.status(), 307);
  assert.equal(new URL(billing.headers().location, base).href, `${base}/fr/account?pending=1`);
  assert.equal(billing.headers()["cache-control"], "private, no-store");
  await page.goto(`${base}/fr/preview/text-decode`, { waitUntil: "domcontentloaded" });
  await page.locator('[data-preview-ready="true"]').waitFor();
  await page.locator("h2 .tdc-cell").first().waitFor();
  const glyphs = await page.locator("h2 .tdc-cell > span:last-child").allTextContents();
  assert.equal(glyphs.join("").replace(/\s/g, ""), "Signaldétectéà1420MHz.");
  await page.screenshot({ path: `${output}/french-glyphs.png` });
  const frenchCopy = { ...JSON.parse(fs.readFileSync("content/site-i18n/fr.json", "utf8")), ...JSON.parse(fs.readFileSync("content/site-i18n-overrides.json", "utf8")).fr };
  await page.goto(`${base}/fr/preview/cta-horizon`, { waitUntil: "domcontentloaded" });
  await page.locator('[data-preview-ready="true"]').waitFor();
  assert.equal((await page.locator("h2").innerText()).replace(/\s+/g, " ").trim(), frenchCopy["Ship the version you’d be proud to demo."], "A word-based headline translates its sentence before splitting");
  await page.goto(`${base}/fr/preview/hero-blur-statement`, { waitUntil: "domcontentloaded" });
  await page.locator('[data-preview-ready="true"]').waitFor();
  const statement = (await page.locator('[data-demo="statement"] > span[aria-hidden="true"]').filter({ visible: true }).innerText()).replace(/\s+/g, " ");
  assert(statement.includes(frenchCopy["We design products for"]));
  assert(statement.includes(frenchCopy["open on purpose."]));
  assert.equal(await page.locator('[data-hero-word="Tessel"]').innerText(), "Tessel", "The rolling brand keeps its official name");
  for (const brand of ["Kiln", "Meridian", "Parcel"]) {
    await page.locator('[data-demo="rotation"]').click();
    assert.equal(await page.locator(`[data-hero-word="${brand}"]`).innerText(), brand, "A brand name must keep its spelling while rotating");
  }
  await page.screenshot({ path: `${output}/french-hero.png` });
  await page.goto(`${base}/fr/preview/diagram-rag-pipeline`, { waitUntil: "domcontentloaded" });
  await page.locator('[data-preview-ready="true"]').waitFor();
  await page.getByText(frenchCopy["Yes. Cancel within 30 days of your renewal and the whole year comes back to your card."], { exact: false }).first().waitFor();
  assert.equal(await page.getByText("Yes. Cancel within 30 days of your renewal", { exact: false }).count(), 0, "Streaming answer words use translated display copy");
  let blockLanguage = true;
  await page.route("**/locale-previews/fr/chart-portfolio.*.json", async (route) => blockLanguage ? route.fulfill({ status: 503, body: "Unavailable" }) : route.continue());
  await page.goto(`${base}/fr/preview/chart-portfolio`, { waitUntil: "domcontentloaded" });
  const retry = page.getByRole("button", { name: /Réessayer|Relancer/i });
  await retry.waitFor();
  blockLanguage = false;
  await retry.click();
  await page.locator('[data-preview-ready="true"]').waitFor();
  await page.getByText("Le mois dernier", { exact: true }).waitFor();
  assert.equal((await page.request.get(`${base}/xx/components`)).status(), 404);
  assert.equal((await page.request.get(`${base}/en/components`, { maxRedirects: 0 })).status(), 308);
  assert.deepEqual(errors, []);
  fs.writeFileSync(`${output}/report.json`, JSON.stringify({ ok: true, results }, null, 2));
  console.log(JSON.stringify({ ok: true, pages: results.length, headers: LOCALES.length, output }));
} finally { await browser.close(); }
