import assert from 'node:assert/strict';
import {launchChromium} from '../../scripts/lib/browser.mjs';
const browser=await launchChromium();
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const base=process.env.TEST_BASE||'http://localhost:3214';
await page.goto(base+'/components');
const cards=page.locator('.component-grid .component-card');await cards.first().waitFor();
const opacity=index=>cards.nth(index).evaluate(e=>getComputedStyle(e,'::after').opacity);
await page.mouse.move(0,0);assert.equal(await opacity(1),'0');
const initial=await cards.nth(1).boundingBox();
await cards.first().hover();assert.equal(await opacity(0),'0');assert.equal(await opacity(1),'0.18');
assert.deepEqual(await cards.nth(1).boundingBox(),initial);
await page.screenshot({path:'test-results/site-performance/gallery-focus.png'});
await page.mouse.move(0,0);assert.equal(await opacity(1),'0');
await page.keyboard.press('Tab');await cards.first().focus();assert.equal(await opacity(1),'0.18');
await context.close();
const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
const phone=await touch.newPage();await phone.goto(base+'/components');
await phone.locator('.component-card').first().waitFor();
assert.equal(await phone.locator('.component-card').nth(1).evaluate(e=>getComputedStyle(e,'::after').opacity),'0');
await browser.close();console.log('Hover, keyboard, touch and stable-layout checks passed.');
